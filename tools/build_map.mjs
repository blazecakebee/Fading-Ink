import { readFileSync, writeFileSync } from 'fs';
import { feature } from 'topojson-client';
const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json'));
const fc = feature(topo, topo.objects.countries);
const ISO = { cn: '156', kr: '410', jp: '392', us: '840', gb: '826', br: '076', ng: '566', in: '356', ru: '643', mx: '484', fr: '250', eg: '818' };
const BBOX = { cn: [73, 18, 135, 54], kr: [124.6, 33.1, 130.9, 38.9], jp: [128.5, 30.5, 146, 45.6], us: [-125, 24, -66, 50], gb: [-8.7, 49.8, 1.9, 59], br: [-74, -34, -34, 5.5], ng: [2.6, 4.2, 14.7, 13.9], in: [68, 6.5, 97.5, 35.5], ru: [27, 42, 95, 68], mx: [-117.5, 14.5, -86.5, 32.8], fr: [-5.2, 42.3, 8.3, 51.1], eg: [24.7, 22, 36.9, 31.7] };
// simplify a ring by dropping points closer than tol degrees to the last kept one
const simp = (ring, tol) => { const out = [ring[0]]; for (const p of ring.slice(1)) { const q = out[out.length - 1]; if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= tol) out.push(p); } if (out.length < 4) return null; return out.map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]); };
// rings that cross the 180° line get shifted onto the side we're looking at (fixes a band across the map)
const fixWrap = (ring, east) => { const crosses = ring.some((p, i) => i && Math.abs(p[0] - ring[i - 1][0]) > 180); return crosses ? ring.map(([x, y]) => [east && x < 0 ? x + 360 : !east && x > 0 ? x - 360 : x, y]) : ring; };
const rings = f => f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates.flat() : [];
const out = {};
for (const [k, bb] of Object.entries(BBOX)) {
  const pad = Math.max(bb[2] - bb[0], bb[3] - bb[1]) * 0.2; const B = [bb[0] - pad, bb[1] - pad, bb[2] + pad, bb[3] + pad];
  const tol = Math.max(bb[2] - bb[0], bb[3] - bb[1]) / 200;
  const shapes = [];
  for (const f of fc.features) {
    const east = (bb[0] + bb[2]) / 2 > 0; const rs = rings(f).map(r => fixWrap(r, east)).filter(r => r.some(([x, y]) => x >= B[0] && x <= B[2] && y >= B[1] && y <= B[3]));
    if (!rs.length) continue;
    const pts = rs.map(r => simp(r, f.id === ISO[k] ? tol : tol * 2.5)).filter(Boolean); if (!pts.length) continue;
    shapes.push({ home: f.id === ISO[k], name: f.properties.name, rings: pts });
  }
  out[k] = shapes;
}
const js = '// Country outlines from Natural Earth (public domain) via world-atlas, simplified. Generated by tools/build_map.mjs\nexport const MAP_SHAPES = ' + JSON.stringify(out) + ';\n';
writeFileSync('/home/claude/fi/js/data/mapShapes.js', js); console.log((js.length / 1024).toFixed(0) + ' KB', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
